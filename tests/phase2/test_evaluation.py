import csv
import json
import tempfile
import unittest
from pathlib import Path
from evaluation.analyze import analyze, common_backlogged_window, percentile, jain
class MetricsTests(unittest.TestCase):
    def test_quantile_definition(self):
        self.assertEqual(percentile([0,10],.5),5)
        self.assertEqual(percentile([0,10],.99),9.9)
        self.assertEqual(jain([1,1,1]),1)
    def test_common_window_only_occupancy(self):
        with tempfile.TemporaryDirectory() as t:
            paths=[]
            for i in range(2):
                p=Path(t)/str(i);p.mkdir();paths.append(p)
                (p/'systemc.wr.csv').write_text('jetty_id\n0\n1\n')
                (p/'systemc.events.csv').write_text('time_ps,event,jetty\n1000,enqueue,0\n'+str(2000+i*1000)+',enqueue,1\n9000,dequeue,0\n10000,dequeue,1\n')
            self.assertEqual(common_backlogged_window(paths),(4,9))
    def test_mixed_golden_event_metrics(self):
        # Existing output is generated by the reproducible script, so this checks
        # a measured baseline; backend is run by the adapter tests separately.
        src=Path('experiments/phase2/output/synthetic_mixed/drr')
        if not src.exists():self.skipTest('run phase2 experiments to check stored measured output')
        with tempfile.TemporaryDirectory() as t:
            import shutil
            for name in ['run.json','systemc.wr.csv','systemc.events.csv']:shutil.copyfile(src/name,Path(t)/name)
            r=analyze(t,2000,6000)
            self.assertAlmostEqual(r['payload_throughput_gbps'],87.04564112748676)
            self.assertAlmostEqual(r['fairness']['wire_jain'],.9998644769689814)
            self.assertAlmostEqual(r['ready_to_complete_ns']['p50'],8225.64)
            late=analyze(t,1000000,2000000)
            self.assertIsNone(late['fairness']['wire_jain'])
            p=Path(t)/'systemc.events.csv';s=p.read_text();p.write_text(s.replace(',complete,',',missing,',1))
            with self.assertRaises(AssertionError):analyze(t,2000,6000)

if __name__=='__main__':unittest.main()

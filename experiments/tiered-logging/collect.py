#!/usr/bin/env python3
"""Create readable measured performance, output sizes, and parity reports."""
import argparse
import csv
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--raw', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    report = json.loads((args.raw / 'results.json').read_text())
    args.out.mkdir(parents=True, exist_ok=True)
    rows = []
    for run in report['runs']:
        host, output = run['host'], run['output']
        summary = run.get('online_summary', run.get('strict_summary', {}))
        metrics = run.get('metrics', {})
        rows.append(dict(case=run['case'], mode=run['mode'],
                         status=host['status'], layer_latency_ps=summary.get('layer_latency_ps'),
                         simulator_events=metrics.get('simulator_events'),
                         wall_seconds=host['wall_seconds'], cpu_seconds=host['cpu_seconds'],
                         user_cpu_seconds=host['user_cpu_seconds'], system_cpu_seconds=host['system_cpu_seconds'],
                         peak_rss_kib=host['peak_rss_kib'], verification_wall_ns=summary.get('verification_wall_ns'),
                         generated_bytes=output['generated_bytes'],
                         generated_file_count=sum(item['category'] not in ('inputs', 'input_metadata') for item in output['files'].values()),
                         total_file_count=len(output['files']),
                         preflight_cpu_seconds=run.get('preflight_host', {}).get('cpu_seconds'),
                         postflight_cpu_seconds=(run.get('postflight_host') or {}).get('cpu_seconds'),
                         strict_verifier_cpu_seconds=(run.get('strict_verifier_host') or {}).get('cpu_seconds'),
                         summary_json_bytes=output['categories']['summary_json'],
                         input_copy_bytes=output['categories']['inputs'],
                         input_metadata_bytes=output['categories'].get('input_metadata', 0),
                         application_events_bytes=output['categories']['application_events'],
                         native_traces_bytes=output['categories']['native_traces'],
                         raw_payload_bytes=output['categories']['raw_payloads'],
                         other_output_bytes=output['categories']['other_outputs']))
    with (args.out / 'measurements.csv').open('w') as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]) if rows else ['status'], lineterminator='\n')
        writer.writeheader()
        writer.writerows(rows)
    (args.out / 'measurements.json').write_text(json.dumps(rows, indent=2) + '\n')
    compact = {'status': report['status'], 'cases': len(report['comparisons']),
               'fault_runs': len(report['faults']),
               'fault_runs_passed': sum(row.get('status') == 'PASS' for row in report['faults']),
               'binary_sha256': report['binary_sha256'],
               'old_binary_sha256': report['old_binary_sha256'],
               'comparisons': report['comparisons']}
    (args.out / 'parity.json').write_text(json.dumps(compact, indent=2) + '\n')
    lines = ['# Tiered logging measurements', '', 'Status: ' + report['status'], '',
             'All measurements below are actual sequential guarded runs, not estimates.',
             'Wall time includes the existing 250 ms guard polling granularity. Tiny-case wall/RSS deltas are not reliable speedup estimates; CPU and the EP64 representative are more informative.',
             'Simulator-generated output bytes exclude copied input fixtures, input-summary metadata emitted by preflight, and post-run strict-verifier artifacts. Per-file breakdowns are in results.json.', '',
             '| Case | Mode | CPU s | Wall s | RSS KiB | Generated bytes | Events |',
             '| --- | --- | ---: | ---: | ---: | ---: | ---: |']
    for row in rows:
        lines.append('| {case} | {mode} | {cpu_seconds:.6f} | {wall_seconds:.3f} | {peak_rss_kib} | {generated_bytes} | {simulator_events} |'.format(**row))
    lines += ['', '## Validation', '',
              f"- {len(report['comparisons'])} same-input case comparisons completed.",
              f"- {compact['fault_runs_passed']}/{compact['fault_runs']} fault-mode runs failed through the expected application guard with FAIL validation.",
              '- Summary/event/debug online summaries, simulator counters, and validation checks are equal after excluding only log_level and verification_wall_ns.',
              '- Full debug is checked by the original independent strict verifier and against the original binary, including exact common artifact bytes.',
              '- Event-only records are independently reconstructed from full debug rows, including documented boundary aliases.',
              '- Preflight checks independently reconstruct routing, quotas, execution input, and the native weight graph before and after every run.', '',
              '## Scope', '', 'This representative matrix does not constitute a rerun of the full token scaling scan. No accepted physics, routing, timing or native protocol settings were changed.']
    (args.out / 'REPORT.md').write_text('\n'.join(lines) + '\n')
    print(json.dumps(compact | {'comparisons': list(report['comparisons'])}, indent=2))


if __name__ == '__main__':
    main()
